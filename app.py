import streamlit as st
import pandas as pd
import joblib
from sklearn.metrics import accuracy_score, precision_score,roc_auc_score, recall_score, f1_score, classification_report, matthews_corrcoef,confusion_matrix
import matplotlib.pyplot as plt
import seaborn as sns

# App Configuration
st.set_page_config(page_title="Machine Learning Model Evaluator", layout="wide")

st.title("📊 Machine Learning Model Evaluation Dashboard -- Diabetes Identification")
st.write("Upload your test dataset and select a trained model to evaluate its performance.")

# --- Requirement B: Model selection dropdown ---
st.sidebar.header("1. Model Selection")
model_options = {
    "Logistic Regression": "model/lr.pkl",
    "KNN": "model/knn.pkl",
    "Support Vector Machine": "model/svm_classifier.pkl",
    "Naive Bayes": "model/nb_classifier.pkl",
    "Decision Tree": "model/dt.pkl"
}
selected_model_name = st.sidebar.selectbox("Choose a trained model", list(model_options.keys()))

# --- Requirement A: Dataset upload option (CSV test data) ---
st.sidebar.header("2. Dataset Upload")
uploaded_file = st.sidebar.file_uploader("Upload Test Data (CSV format)", type=["csv"])

if uploaded_file is not None:
    # Load test data
    test_df = pd.read_csv(uploaded_file)

    with st.expander("Preview Uploaded Test Data"):
        st.dataframe(test_df.head())

    # Select target/label column
    target_column = st.selectbox("Select your Target / Label Column", test_df.columns)

    if target_column:
        X_test = test_df.drop(columns=[target_column])
        y_test = test_df[target_column]

        try:
            # Load the selected pre-trained model
            model_file = model_options[selected_model_name]
            model = joblib.load(model_file)

            # Make predictions
            y_pred = model.predict(X_test)
            y_proba = model.predict_proba(X_test)[:, 1] # Probabilities for the positive class (needed for AUC)

            # --- Requirement C: Display of evaluation metrics ---
            st.markdown("---")
            st.subheader(f"📈 Evaluation Metrics for: {selected_model_name}")

            acc = accuracy_score(y_test, y_pred)
            auc_score = roc_auc_score(y_test, y_proba)
            prec = precision_score(y_test, y_pred, average='weighted', zero_division=0)
            rec = recall_score(y_test, y_pred, average='weighted', zero_division=0)
            f1 = f1_score(y_test, y_pred, average='weighted', zero_division=0)
            mcc = matthews_corrcoef(y_test, y_pred)

            col1, col2, col3, col4,col5,col6= st.columns(6)
            col1.metric("Accuracy", f"{acc:.4f}")
            col2.metric("AUC", f"{auc_score:.4f}")
            col3.metric("Precision", f"{prec:.4f}")
            col4.metric("Recall", f"{rec:.4f}")
            col5.metric("F1 Score", f"{f1:.4f}")
            col6.metric("MCC", f"{mcc:.4f}")

            st.markdown("---")

            # --- Requirement D: Confusion Matrix & Classification Report ---
            col_left, col_right = st.columns(2)

            with col_left:
                st.subheader("📋 Classification Report")
                report_dict = classification_report(y_test, y_pred, output_dict=True)
                report_df = pd.DataFrame(report_dict).transpose()
                st.dataframe(report_df.style.format("{:.4f}"))

            with col_right:
                st.subheader("📉 Confusion Matrix")
                fig, ax = plt.subplots(figsize=(5, 4))
                cm = confusion_matrix(y_test, y_pred)
                sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', ax=ax, cbar=False)
                ax.set_xlabel("Predicted Label")
                ax.set_ylabel("True Label")
                st.pyplot(fig)

        except FileNotFoundError:
            st.error(f"❌ Model file **'{model_options[selected_model_name]}'** not found in the directory. Please export and save your trained model first.")
        except Exception as e:
            st.error(f"An error occurred during prediction: {e}")
else:
    st.info("👈 Please upload your test dataset CSV file using the sidebar to get started.")
